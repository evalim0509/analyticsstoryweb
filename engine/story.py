MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
WHO = re.compile(r"customer|client|segment|account|sales ?rep|salesperson|owner|manager|employee|staff|team|buyer|supplier|vendor|member|agent|person", re.I)
LEAD = ["sales", "revenue", "amount", "profit", "margin", "income", "actual", "cost", "expense", "spend", "value", "total", "quantity", "units", "volume"]
NOT_ADDITIVE = re.compile(r"price|rate|score|percent|%|discount|tenure|\bage\b|ratio|rating|year", re.I)
TARGET = re.compile(r"target|budget|plan|goal|quota", re.I)
LOWER_IS_BETTER = re.compile(r"cost|expense|spend|overhead|complaint|return|refund|ticket", re.I)


def _short(v):
    """Numbers the way people say them: 1.52M, 188K, 742."""
    if v is None:
        return "nothing"
    a = abs(v)
    if a >= 1e9:
        return f"{v / 1e9:.2f}B"
    if a >= 1e6:
        return f"{v / 1e6:.2f}M"
    if a >= 1e4:
        return f"{v / 1e3:.0f}K"
    return f"{v:,.0f}" if a >= 100 or v == int(v) else f"{v:,.2f}"


def _pct(cur, old):
    return None if not old else 100.0 * (cur - old) / abs(old)


def _move(cur, old, neutral=False, unit=""):
    """'8% ahead of' / '3% behind' / 'level with'. Cost-like numbers get the neutral 'above' / 'below'.
    A measure that is itself a percentage moves in points."""
    up, down = ("above", "below") if neutral else ("ahead of", "behind")
    if unit == "%":
        if old is None:
            return None
        d = cur - old
        return "level with" if abs(d) < 0.05 else f"{abs(d):.1f} points {up if d > 0 else down}"
    p = _pct(cur, old)
    if p is None:
        return None
    if abs(p) < 0.5:
        return "level with"
    return f"{abs(p):.0f}% {up if p > 0 else down}"


def _mood(change, lower_better, flat=1.0):
    """'good', 'bad' or 'neutral' for a change in percent. For cost-like numbers a rise is bad."""
    if change is None or abs(change) < flat:
        return "neutral"
    return "good" if (change > 0) != lower_better else "bad"


def _signed(v):
    return ("+" if v >= 0 else "−") + _short(abs(v))


def _join(parts):
    parts = list(parts)
    return parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]


def _mlabel(m):
    return f"{MON[m % 12]} {m // 12}"


def _lookup_tables():
    ids = {l["b"] for l in store.LINKS}
    return ids | {s["b"] for s in joins.suggest()}


def options():
    """The things a story can be about, in plain words: main totals, derived measures, an average, the row count."""
    lookups = _lookup_tables()
    facts = [d for d in store.DATASETS.values() if d["kind"] == "table" and d["id"] not in lookups]
    facts.sort(key=lambda d: (not any(c["type"] == "date" for c in d["columns"]), -d["rows"]))
    out = []
    for base in facts:
        view = next((d for d in store.DATASETS.values() if d["kind"] == "linked" and d["base"] == base["id"]), base)
        items = MS.listing(view, base)
        group = lambda i: "count" if not i["value"] else "calc" if str(i["value"]).startswith("calc:") else "average" if i["label"] == f"Average {i['value']}" else "total"
        pick = [i for i in items if group(i) == "total"][:2 if len(facts) > 1 else 3] + [i for i in items if group(i) == "calc"][:3] \
            + [i for i in items if group(i) == "average"][:1] + [i for i in items if group(i) == "count"]
        out += [{"dataset": view["id"], "value": i["value"], "label": i["label"], "detail": i["detail"]} for i in pick]
    return out[:8]


def tidy_status():
    fixes = 0
    for d in store.DATASETS.values():
        if d["kind"] == "table":
            fixes += sum(1 for i in quality.check(d["id"])["issues"] if i["fix"] and i["confidence"] == "High" and i["kind"] != "missing")
    review = sum(quality.check(d["id"])["summary"]["to_review"] for d in store.DATASETS.values() if d["kind"] == "table")
    return {"fixes": fixes, "links": sum(1 for j in joins.suggest() if j["confidence"] == "High"), "to_review": review}


def tidy_all():
    """One click: apply every high-confidence fix, then link every high-confidence pair of tables."""
    done = []
    for d in list(store.DATASETS.values()):
        if d["kind"] != "table":
            continue
        for _ in range(40):
            todo = [i for i in quality.check(d["id"])["issues"] if i["fix"] and i["confidence"] == "High" and i["kind"] != "missing"]
            if not todo:
                break
            done.append(quality.apply_fix(d["id"], todo[0]["key"]).get("text"))
    for _ in range(20):
        sure = [j for j in joins.suggest() if j["confidence"] == "High"]
        if not sure:
            break
        joins.accept(sure[0]["key"])
        done.append(f"Linked {sure[0]['a_name']} to {sure[0]['b_name']} using {sure[0]['a_col']}.")
    return done


class _Run:
    """Runs queries for one story and remembers them for 'How I got this'."""
    def __init__(self, ds, expr, where, params, date):
        self.ds, self.expr, self.where, self.params, self.date = ds, expr, where, params, date
        self.t = q(ds["table"])
        d = q(date) if date else None
        self.mi = f"(CAST(strftime('%Y', {d}) AS INTEGER) * 12 + CAST(strftime('%m', {d}) AS INTEGER) - 1)" if date else None
        self.sql = {}

    def _cond(self, a=None, b=None):
        parts = [self.where[7:]] if self.where else []
        params = list(self.params)
        if a is not None:
            parts.append(f"{self.mi} BETWEEN ? AND ?")
            params += [a, b]
        return (" WHERE " + " AND ".join(parts) if parts else ""), params

    def total(self, a=None, b=None, card=None):
        w, p = self._cond(a, b)
        sql = f"SELECT {self.expr} FROM {self.t}{w}"
        if card:
            self.sql.setdefault(card, builder.pretty_sql(sql, p))
        return scalar(sql, p) or 0

    def count(self, a=None, b=None):
        w, p = self._cond(a, b)
        return scalar(f"SELECT COUNT(*) FROM {self.t}{w}", p) or 0

    def by(self, dim, a=None, b=None, card=None, min_n=0):
        w, p = self._cond(a, b)
        having = f" HAVING COUNT(*) >= {int(min_n)}" if min_n else ""
        sql = f"SELECT {q(dim)}, {self.expr} FROM {self.t}{w} GROUP BY 1{having} ORDER BY 2 DESC"
        if card:
            self.sql.setdefault(card, builder.pretty_sql(sql, p))
        return [(("not recorded" if k is None else str(k)), v or 0) for k, v in rows(sql, p)]

    def months(self, card=None):
        w, p = self._cond()
        w = (w + " AND " if w else " WHERE ") + f"{q(self.date)} IS NOT NULL"
        sql = f"SELECT {self.mi}, {self.expr}, MAX(CAST(strftime('%d', {q(self.date)}) AS INTEGER)), COUNT(*) FROM {self.t}{w} GROUP BY 1 ORDER BY 1"
        if card:
            self.sql.setdefault(card, builder.pretty_sql(sql, p))
        return rows(sql, p)


def _dims(ds, base):
    """Fields that say who, and fields that say which."""
    who, which = [], []
    names = {c["name"].lower() for c in ds["columns"]}
    for c in ds["columns"]:
        if c["role"] not in ("category", "id", "text") or c["type"] == "date" or c["distinct"] < 2:
            continue
        if c["distinct"] > 0.5 * ds["rows"] or c["distinct"] > 2000:
            continue                                   # different on almost every row: not a grouping
        n = c["name"]
        stem = re.sub(r"\s*(id|code|no|number)$", "", n, flags=re.I).strip().lower()
        if stem != n.lower() and (stem + " name") in names:
            continue                                   # prefer "Customer Name" over "Customer ID"
        if TARGET.search(n):
            continue
        is_who = WHO.search(n) and not re.search(r"product|item|sku|categor", n, re.I)
        (who if is_who else which).append(c)
    pinned_who = [CAT.role(k, ds) for k in ("customer", "rep")]
    pinned_which = [CAT.role(k, ds) for k in ("product", "region")]
    for c in list(who):
        if c["name"] in pinned_which:
            who.remove(c); which.append(c)
    for c in list(which):
        if c["name"] in pinned_who:
            which.remove(c); who.append(c)
    have = {c["name"] for c in who + which}
    for c in ds["columns"]:               # a matched column is used even when its name gives no hint
        if c["name"] not in have and c["distinct"] >= 2 and c["type"] != "date" and c["name"] in pinned_who + pinned_which:
            (who if c["name"] in pinned_who else which).append(c)
    who.sort(key=lambda c: (c["distinct"] > 15, c["name"] not in pinned_who, pinned_who.index(c["name"]) if c["name"] in pinned_who else 0, c["distinct"]))
    hints = ["product", "categor", "region", "channel", "department", "type", "brand", "store", "branch", "country"]
    which.sort(key=lambda c: (c["distinct"] > 40, c["name"] not in pinned_which, pinned_which.index(c["name"]) if c["name"] in pinned_which else 0, next((i for i, h in enumerate(hints) if h in c["name"].lower()), 50), c["distinct"]))
    return [c["name"] for c in who], [c["name"] for c in which]


def _breakdown(run, dim, cur, prev, card, min_n=0):
    now = run.by(dim, cur[0], cur[1], card, min_n) if cur else run.by(dim, card=card, min_n=min_n)
    before = dict(run.by(dim, prev[0], prev[1], min_n=min_n)) if prev else {}
    total = sum(v for _, v in now) or 1
    out = []
    for name, v in now:
        out.append({"name": name, "value": v, "share": 100.0 * v / total, "before": before.get(name),
                    "change": _pct(v, before.get(name)) if prev else None})
    gone = [(k, v) for k, v in before.items() if k not in {n for n, _ in now} and v]
    return out, total, gone


def _movers(items, total):
    big = [i for i in items if i["change"] is not None and max(i["value"], i["before"] or 0) >= 0.03 * total and i["name"] != "not recorded"]
    if len(big) < 2:
        return None, None
    up, down = max(big, key=lambda i: i["value"] - i["before"]), min(big, key=lambda i: i["value"] - i["before"])
    return (up if up["value"] > up["before"] else None), (down if down["value"] < down["before"] else None)


def _find_target(ds, base):
    """A target or budget table that shares a field with the story's data."""
    names = {c["name"].lower(): c["name"] for c in ds["columns"]}
    for t in store.DATASETS.values():
        if t["kind"] != "table" or t["id"] == base["id"] or t["rows"] > 500:
            continue
        tcol = next((c["name"] for c in t["columns"] if c["type"] == "number" and (c["name"] == CAT.role("target") or TARGET.search(c["name"]) or TARGET.search(t["name"])) and c["role"] != "id"), None)
        key = next((c["name"] for c in t["columns"] if c["type"] == "text" and c["name"].lower() in names and c["distinct"] == t["rows"]), None)
        if tcol and key:
            year = re.search(r"(20\d\d)", tcol) or re.search(r"(20\d\d)", t["name"])
            return {"table": t, "col": tcol, "key": key, "dim": names[key.lower()], "year": int(year.group(1)) if year else None}
    return None


def _chart_choice(spec, key, kinds):
    want = (spec.get("charts") or {}).get(key)
    return want if want in [k for k, _ in kinds] else kinds[0][0]


def build(spec):
    ds = store.DATASETS[spec["dataset"]]
    base = store.DATASETS[ds.get("base", ds["id"])]
    value = spec.get("value")
    M = MS.define(ds, base, value)
    label, of_what, expr, unit = M["label"], M["of"], M["expr"], M["unit"]
    filters = [f for f in (spec.get("filters") or []) if f.get("value")]
    where, params, fwords = builder.where_clause(ds, filters)
    for cur_info in base.get("currency") or []:
        affected = (cur_info["column"] == "*" and M["kind"] != "count" and value) or (cur_info["column"] != "*" and q(cur_info["column"]) in M["expr"])
        pinned = any(f["field"] == cur_info["field"] and len(f.get("value") or []) == 1 for f in filters)
        if affected and not pinned:
            what = "these amounts" if cur_info["column"] == "*" else cur_info["column"]
            return {"error": f"{what[0].upper() + what[1:]} {'are' if cur_info['column'] == '*' else 'is'} in more than one currency ({', '.join(cur_info['codes'])}). "
                             "Gist does not add different currencies together. Choose one currency to see the story.",
                    "currency": {"field": cur_info["field"], "codes": cur_info["codes"]}}
    dates = [c["name"] for c in base["columns"] if c["type"] == "date"]
    date = spec.get("date") if spec.get("date") in dates else MS.chosen_date(base)
    run = _Run(ds, expr, where, params, date)
    lower_better = bool(LOWER_IS_BETTER.search(label)) and M["kind"] != "ratio"

    def short(v):                       # figures the way people say them; percentages with one decimal
        return "nothing" if v is None else f"{v:.1f}%" if unit == "%" else _short(v)

    def moodof(up):
        return "good" if up != lower_better else "bad"

    def chip(cur_v, old_v, against):
        """A coloured change marker for a sentence: '▼ 5% vs Q2 2025'."""
        if old_v is None:
            return None
        if unit == "%":
            d = cur_v - old_v
            flat, text = abs(d) < 0.05, f"{abs(d):.1f} pts vs {against}"
        else:
            p_ = _pct(cur_v, old_v)
            if p_ is None:
                return None
            flat, text = abs(p_) < 0.5, f"{abs(p_):.0f}% vs {against}"
        if flat:
            return {"chip": f"level with {against}", "dir": "flat", "mood": "neutral"}
        return {"chip": text, "dir": "up" if cur_v > old_v else "down", "mood": moodof(cur_v > old_v)}

    def B(text, up=None):
        """A bullet. **bold** marks names and figures; up=True/False adds an arrow coloured by meaning."""
        return {"t": text, "dir": None if up is None else ("up" if up else "down"), "mood": None if up is None else moodof(up)}
    scope = f" (only where {' and '.join(fwords)})" if fwords else ""
    start = f"Started with “{ds['name']}” ({ds['rows']:,} rows)" + (f", keeping only rows where {' and '.join(fwords)}." if fwords else ".")
    who_dims, which_dims = _dims(ds, base)
    narrowed = {f["field"] for f in filters}          # a field the story is narrowed to has only one value left
    who_dims = [d for d in who_dims if d not in narrowed]
    which_dims = [d for d in which_dims if d not in narrowed]
    filter_fields = [{"field": c["name"], "values": builder.field_values(ds["id"], c["name"], 30)}
                     for c in ds["columns"] if c["role"] == "category" and c["type"] == "text" and 2 <= c["distinct"] <= 30][:8]
    try:
        fs0 = (int(spec.get("fiscal_start") or 1) - 1) % 12      # month the business year starts in, 0 = January
    except (TypeError, ValueError):
        fs0 = 0

    def qlabel(end):
        """A quarter by its last month. With a business year that does not start in January the months
        are spelled out, because there is no single convention for naming such a year."""
        n = ((end - fs0) % 12) // 3 + 1
        if fs0 == 0:
            return f"Q{n} {end // 12}"
        a = end - 2
        return f"Q{n} ({MON[a % 12]}{'' if a // 12 == end // 12 else ' ' + str(a // 12)}–{MON[end % 12]} {end // 12})"

    # ---------------- time frame
    cur = prev = yoy = None
    series, notes, period_kind, periods = [], [], None, []
    if date in (base.get("combined") or {}):
        first_d, second_d = base["combined"][date]
        notes.append(f"Used {first_d} for the date, and {second_d} where {first_d} was blank.")
    order = (base.get("date_orders") or {}).get(date)
    if order and order.get("ambiguous"):
        notes.append(f"Read the dates in {date} as {'day/month' if order['order'] == 'dmy' else 'month/day'}; the file itself cannot tell.")
    plabel = "all the data"
    prev_label = yoy_label = None
    if date:
        raw = run.months("when")
        if raw:
            runs, block = [], [raw[0]]
            for r in raw[1:]:
                if r[0] - block[-1][0] > 6:
                    runs.append(block); block = [r]
                else:
                    block.append(r)
            runs.append(block)
            main = max(runs, key=lambda b: sum(r[3] for r in b))
            stray = sum(r[3] for b in runs if b is not main for r in b)
            if stray:
                notes.append(f"Ignored {stray} row{'s' if stray != 1 else ''} with dates far away from all the others.")
            first, last = main[0][0], main[-1][0]
            done, why = MS.month_complete(base, date, last, main[-1][2])
            if not done and last - first > 3:
                notes.append(f"Left out {_mlabel(last)}. {why}")
                last -= 1
            got = {r[0]: r[1] or 0 for r in main}
            series = [(m, got.get(m, 0)) for m in range(first, last + 1)]
            n_months = last - first + 1
            off = (last - fs0) % 3
            q_end = last if off == 2 else last - (off + 1)
            periods = [{"key": "month", "label": _mlabel(last)}]
            if q_end - 2 >= first:
                periods.append({"key": "quarter", "label": qlabel(q_end)})
            if n_months >= 12:
                periods.append({"key": "year", "label": f"the 12 months to {_mlabel(last)}"})
            keys = [p["key"] for p in periods]
            period_kind = spec.get("period") if spec.get("period") in keys else ("quarter" if "quarter" in keys else "month")
            if period_kind == "month":
                cur = (last, last)
            elif period_kind == "quarter":
                cur = (q_end - 2, q_end)
            else:
                cur = (last - 11, last)
            plabel = next(p["label"] for p in periods if p["key"] == period_kind)
            n = cur[1] - cur[0] + 1
            if cur[0] - n >= first:
                prev = (cur[0] - n, cur[1] - n)
                prev_label = _mlabel(prev[0]) if n == 1 else qlabel(prev[1]) if n == 3 else "the 12 months before"
            if cur[0] - 12 >= first and n < 12:
                yoy = (cur[0] - 12, cur[1] - 12)
                yoy_label = _mlabel(yoy[0]) if n == 1 else qlabel(yoy[1])
    cards = []

    # ---------------- WHAT
    now = run.total(*(cur or (None, None)), card="what")
    if not ds["rows"] or (cur is None and date and not series):
        return {"error": "There are no rows to tell a story about with this choice."}
    pv = run.total(*prev) if prev else None
    table, chart_pts, more = [[plabel, now, None]], [], []
    bits = []
    if prev:
        mv = _move(now, pv, lower_better, unit)
        if mv:
            bits.append(f"{mv} {prev_label}")
        table.append([prev_label, pv, _pct(now, pv)])
        chart_pts.append((prev_label, pv))
        if pv and now != pv:
            more.append(B((f"**{abs(now - pv):.1f} points {'higher' if now >= pv else 'lower'}**" if unit == "%" else f"**{short(abs(now - pv))} {'more' if now >= pv else 'less'}**")
                          + f" than {prev_label}, which closed at **{short(pv)}**", now > pv))
    if yoy:
        yv = run.total(*yoy)
        mv = _move(now, yv, lower_better, unit)
        if mv:
            bits.append(f"{mv} {yoy_label}")
        table.append([yoy_label, yv, _pct(now, yv)])
        chart_pts.insert(0, (yoy_label, yv))
    what_parts = None
    if cur:
        s = f"{label} {'came to' if pv and now < pv else 'reached'} {short(now)} in {plabel}" + (", " + " and ".join(bits) if bits else "") + "."
        what_parts = [f"{label} {'came to' if pv and now < pv else 'reached'} {short(now)} in {plabel}"] + [c_ for c_ in (chip(now, pv, prev_label) if prev else None, chip(now, yv, yoy_label) if yoy else None) if c_]
    else:
        s = f"{label} {'totalled' if M['additive'] else 'came to'} {short(now)} across all the data."
    chart_pts.append((plabel, now))
    target = _find_target(ds, base) if M["column"] and M["additive"] and date and series else None
    if target:
        # A target only applies to the number it was set for: "Sales Target" is not compared with Quantity.
        # A target with no subject in its name ("Target 2025") is read as the main number's target.
        words = lambda t: {w for w in re.findall(r"[a-z]+", t.lower()) if len(w) > 2 and not TARGET.fullmatch(w)} - {"amount", "total", "value", "year", "annual"}
        about = words(target["col"]) or words(target["table"]["name"])
        mine = words(value)
        if not ((about & mine) if about and mine else value == MS.listing(ds, base)[0]["value"]):
            target = None
    tinfo = None
    if target and all(f["field"] == target["dim"] for f in filters):
        year = target["year"] or ((series[-1][0] - fs0) // 12)
        ya = year * 12 + fs0
        yb = min(ya + 11, series[-1][0])
        if yb >= ya and yb >= series[0][0]:
            actual = dict(run.by(target["dim"], ya, yb))
            wanted = filters[0]["value"] if filters else None
            trows = [(k, v) for k, v in rows(f"SELECT {q(target['key'])}, {q(target['col'])} FROM {q(target['table']['table'])}") if v and (not wanted or k in wanted)]
            pace = 100.0 * (yb - ya + 1) / 12
            left = 11 - (yb - ya)
            items = [{"name": k, "actual": actual.get(k, 0), "target": v, "reached": 100.0 * actual.get(k, 0) / v,
                      "need": (v - actual.get(k, 0)) / left if left > 0 else None, "avg": actual.get(k, 0) / (yb - ya + 1)} for k, v in trows]
            if items:
                ta, tt = sum(i["actual"] for i in items), sum(i["target"] for i in items)
                word = TARGET.search(target["col"]) or TARGET.search(target["table"]["name"])
                word = word.group(0).lower()
                ylabel = str(year) if fs0 == 0 else f"the year from {_mlabel(ya)}"
                tinfo = {"items": items, "pace": pace, "year": ylabel, "actual": ta, "target": tt, "reached": 100.0 * ta / tt, "word": word,
                         "dim": target["dim"], "source": target["table"]["name"], "left": left}
                state = "ahead of" if tinfo["reached"] > pace + 3 else "behind" if tinfo["reached"] < pace - 3 else "in line with"
                more.append(B(f"{ylabel} to date: **{short(ta)}** against a {word} of **{short(tt)}**, **{tinfo['reached']:.0f}% delivered** with {pace:.0f}% of the year gone, {state} the pace required",
                              None if state == "in line with" else (state == "ahead of") != lower_better))
    if M.get("coverage") is not None and M["coverage"] < 0.9:
        more.insert(0, {"t": f"Cost is known for only **{M['coverage']:.0%}** of {M['a_name']}, so this covers those sales only", "dir": None, "mood": "bad", "warn": True})
    steps = [start] + notes + ([M["formula"]] if M["formula"] else []) + [f"{M['verb']} for {plabel}."]
    if prev or yoy:
        steps.append("Did the same for " + " and ".join(x for x in (prev_label, yoy_label) if x) + ", and compared.")
    if tinfo:
        steps.append(f"Compared {tinfo['year']} so far with the {tinfo['word']} in “{tinfo['source']}”.")
    cards.append({"key": "what", "word": "What", "ask": "What happened?", "sentence": s, "parts": what_parts, "more": more, "brief": {"text": f"{short(now)} in {plabel}"},
                  "hero": {"big": short(now), "small": plabel if cur else "across all the data", "value": now}, "mood": _mood(_pct(now, pv) if prev else None, lower_better),
                  "chart": {"type": "bar", "labels": [p[0] for p in chart_pts], "series": [{"name": label, "data": [p[1] for p in chart_pts]}], "x_title": "", "y_title": label, "time": True,
                            "values": True, "mood_last": (chip(now, pv, "") or {}).get("mood") if prev else None} if len(chart_pts) > 1 else None,
                  "table": {"columns": ["Period", label, "Change to now"], "rows": [[r[0], r[1], None if r[2] is None else round(r[2], 1)] for r in table],
                            "meta": {"pct": [2], "up_good": not lower_better}},
                  "steps": steps, "sql": run.sql.get("what")})

    # ---------------- WHO and WHICH (left out when the data has no such field)
    moves = []
    SHARE = [("bars", "Bars"), ("share", "Share of the total")]

    def dim_card(key, word, ask, dims, chosen):
        if not dims:
            return None
        dim = chosen if chosen in dims else dims[0]
        items, total, gone = _breakdown(run, dim, cur, prev, key, 0 if M["additive"] else 3)
        if not items:
            return None
        named = [i for i in items if i["name"] != "not recorded"] or items
        top = named[0]
        more = []
        if not M["additive"]:
            return ratio_card(key, word, ask, dims, dim, items, named)
        if len(items) == 1:
            s = f"{top['name']} was the only {dim} recorded, at {short(top['value'])}."
        else:
            s = f"{top['name']} accounted for {top['share']:.0f}% of {of_what}, the largest share of any {dim}."
            more.append(B(f"**{short(top['value'])}** of **{short(total)}**" + (f" in {plabel}" if cur else "")))
        if len(items) > 4:
            more.append(B(f"The three largest of {len(items):,} together: **{sum(i['share'] for i in items[:3]):.0f}%**"))
        elif len(named) > 1:
            more.append(B(f"**{named[-1]['name']}** was the smallest: {short(named[-1]['value'])} ({named[-1]['share']:.0f}%)"))
        up, down = _movers(items, total) if prev else (None, None)
        if up:
            more.append(B(f"**{up['name']}** gained the most vs {prev_label}: **{_signed(up['value'] - up['before'])}** ({abs(up['change']):.0f}%)", True))
        if down:
            more.append(B(f"**{down['name']}** lost the most vs {prev_label}: **{_signed(down['value'] - down['before'])}** ({abs(down['change']):.0f}%)", False))
        moves.append({"dim": dim, "up": up, "down": down, "top": top, "count": len(items)})
        kind = _chart_choice(spec, key, SHARE)
        keep = 5 if kind == "share" else 8
        shown = items[:keep]
        rest = sum(i["value"] for i in items[keep:]) if kind == "share" else 0     # a ring needs the rest; bars compare the leaders
        labels = [i["name"] for i in shown] + (["All others"] if rest else [])
        data = [i["value"] for i in shown] + ([rest] if rest else [])
        cols = [dim, label, "Share of total"] + ([f"vs {prev_label}"] if prev else [])
        trows = [[i["name"], i["value"], round(i["share"], 1)] + ([None if i["change"] is None else round(i["change"], 1)] if prev else []) for i in items[:200]]
        steps = [start] + notes + ([M["formula"]] if M["formula"] else []) + [f"Grouped the rows for {plabel} by {dim} and {'counted them' if not value else ('added up ' + label if M['column'] else 'worked out ' + label)}.",
                                   "Worked out each group's share of the total."]
        if prev:
            steps.append(f"Did the same for {prev_label} to see who rose and fell. Small groups (under 3% of the total) are not named as risers or fallers.")
        return {"key": key, "word": word, "ask": ask, "sentence": s, "more": more, "dims": dims, "dim": dim,
                "hero": {"big": f"{top['share']:.0f}%", "small": f"{top['name']}, of {of_what}", "value": round(top["share"], 1)} if len(items) > 1 else {"big": short(top["value"]), "small": top["name"], "value": top["value"]},
                "chart_types": [{"key": k, "label": l} for k, l in SHARE] if len(items) > 1 else [], "chart_type": kind,
                "chart": {"type": "share" if kind == "share" else "hbar", "labels": labels, "series": [{"name": label, "data": data}], "x_title": dim, "y_title": label,
                          "values": True, "highlight": labels.index(top["name"]) if top["name"] in labels else 0} if len(items) > 1 else None,
                "table": {"columns": cols, "rows": trows, "meta": {"share": 2, "pct": [3] if prev else [], "up_good": not lower_better}}, "steps": steps, "sql": run.sql.get(key)}

    def ratio_card(key, word, ask, dims, dim, items, named):
        """Who / Which for an average or a ratio: highest and lowest groups; shares of a total do not apply."""
        top, low = named[0], named[-1]
        s = f"{top['name']} had the highest {label} of any {dim}, at {short(top['value'])}." if len(named) > 1 else f"{top['name']} was the only {dim} recorded, at {short(top['value'])}."
        more = [B(f"**{low['name']}** was the lowest: **{short(low['value'])}**")] if len(named) > 1 else []
        moved = [i for i in named if i["change"] is not None and i["before"]]
        if prev and len(moved) > 1:
            up = max(moved, key=lambda i: i["value"] - i["before"]); down = min(moved, key=lambda i: i["value"] - i["before"])
            if up["value"] > up["before"]:
                more.append(B(f"**{up['name']}** rose the most vs {prev_label}: {short(up['before'])} to **{short(up['value'])}**", True))
            if down["value"] < down["before"]:
                more.append(B(f"**{down['name']}** fell the most vs {prev_label}: {short(down['before'])} to **{short(down['value'])}**", False))
        shown = items[:8]
        cols = [dim, label] + ([f"vs {prev_label}"] if prev else [])
        chg = lambda i: None if i["before"] is None else round(i["value"] - i["before"], 1) if unit == "%" else (None if i["change"] is None else round(i["change"], 1))
        trows = [[i["name"], round(i["value"], 2)] + ([chg(i)] if prev else []) for i in items[:200]]
        steps = [start] + notes + ([M["formula"]] if M["formula"] else []) + [f"Grouped the rows for {plabel} by {dim} and worked out {label} for each group.",
                 "Left out groups with fewer than 3 rows, because an average of one or two rows says little."]
        return {"key": key, "word": word, "ask": ask, "sentence": s, "more": more, "dims": dims, "dim": dim, "chart_types": [], "chart_type": "bars",
                "hero": {"big": short(top["value"]), "small": f"{top['name']}, the highest", "value": top["value"]},
                "chart": {"type": "hbar", "labels": [i["name"] for i in shown], "series": [{"name": label, "data": [i["value"] for i in shown]}], "x_title": dim, "y_title": label,
                          "values": True, "unit": unit, "highlight": [i["name"] for i in shown].index(top["name"]) if top["name"] in [i["name"] for i in shown] else 0} if len(items) > 1 else None,
                "table": {"columns": cols, "rows": trows, "meta": {"pct" if unit != "%" else "pts": [2] if prev else [], "up_good": not lower_better}}, "steps": steps, "sql": run.sql.get(key),
                "brief": {"text": s}}

    who_card = dim_card("who", "Who", "Who is behind it?", who_dims, spec.get("who"))
    if who_card:
        cards.append(who_card)

    # ---------------- WHEN (left out when there are no dates, or too little history)
    if series and len(series) >= 3:
        y = np.array([v for _, v in series], dtype=float)
        n = len(y)
        slope = float(np.polyfit(np.arange(n), y, 1)[0])
        yearly = 100 * slope * 12 / (abs(y.mean()) or 1)
        trend = f"has risen by about {abs(yearly):.0f}% a year" if yearly > 3 else f"has fallen by about {abs(yearly):.0f}% a year" if yearly < -3 else "has held broadly steady"
        s = f"{label} {trend} over the {n} months from {_mlabel(series[0][0])} to {_mlabel(series[-1][0])}."
        span_words = f"over the {n} months from {_mlabel(series[0][0])} to {_mlabel(series[-1][0])}"
        when_parts = [label, {"chip": f"about {abs(yearly):.0f}% a year", "dir": "up" if yearly > 0 else "down", "mood": moodof(yearly > 0)} if abs(yearly) > 3 else
                      {"chip": "broadly steady", "dir": "flat", "mood": "neutral"}, span_words]
        more = []
        if n >= 24:
            detr = y - np.polyval(np.polyfit(np.arange(n), y, 1), np.arange(n))
            by_m = [float(np.mean([detr[i] for i in range(n) if series[i][0] % 12 == k] or [0])) for k in range(12)]
            if (max(by_m) - min(by_m)) / (abs(y.mean()) or 1) > 0.1:
                more.append(B(f"Yearly rhythm: **{MON[int(np.argmax(by_m))]}** is usually the strongest month, **{MON[int(np.argmin(by_m))]}** the weakest"))
        hi, lo = int(np.argmax(y)), int(np.argmin(y))
        more.append(B(f"Strongest month: **{_mlabel(series[hi][0])}**, at **{short(float(y[hi]))}**"))
        more.append(B(f"Weakest month: **{_mlabel(series[lo][0])}**, at **{short(float(y[lo]))}**"))
        if n > 12:
            mv = _move(float(y[-1]), float(y[-13]), lower_better, unit)
            if mv:
                more.append(B(f"Latest month, **{_mlabel(series[-1][0])}**: **{short(float(y[-1]))}**, {mv} the same month a year earlier", None if mv == "level with" else float(y[-1]) > float(y[-13])))
        TIME = [("line", "Line"), ("bars", "Bars")]
        kind = _chart_choice(spec, "when", TIME)
        trows = [[_mlabel(m), v, (round(_pct(v, series[i - 12][1]), 1) if i >= 12 and series[i - 12][1] else None)] for i, (m, v) in enumerate(series)]
        cards.append({"key": "when", "word": "When", "ask": "When did it happen?", "sentence": s, "parts": when_parts, "more": more, "mood": _mood(yearly, lower_better, 3),
                      "hero": {"big": short(float(y[-1])), "small": f"in {_mlabel(series[-1][0])}, the latest month", "value": float(y[-1])},
                      "dims": dates, "dim": date, "dim_word": "Date used",
                      "chart_types": [{"key": k, "label": l} for k, l in TIME], "chart_type": kind,
                      "chart": {"type": "line" if kind == "line" else "bar", "labels": [_mlabel(m) for m, _ in series], "series": [{"name": label, "data": [v for _, v in series]}], "x_title": "", "y_title": label, "time": True, "highlight_last": True},
                      "table": {"columns": ["Month", label, "vs a year earlier"], "rows": trows[::-1], "meta": {"pct": [2], "up_good": not lower_better}},
                      "steps": [start] + notes + [f"Worked out {label} for every month using {date}.", "Fitted a straight line through the months to measure the direction.",
                                                  "Compared the same calendar months across years to look for a yearly rhythm."], "sql": run.sql.get("when")})

    which_card = dim_card("which", "Which", "Which ones matter most?", which_dims, spec.get("which"))
    if which_card:
        cards.append(which_card)

    # ---------------- WHY: which groups the change came from (left out with no earlier period or no grouping)
    why_card = None
    why_dims = (who_dims + which_dims)[:8]
    if prev and why_dims and M["additive"]:
        delta = now - pv
        flat = pv is not None and (delta == 0 or (pv and abs(delta) / abs(pv) < 0.005))
        sign = 0 if flat else (1 if delta > 0 else -1)
        per = {}
        for d in why_dims:
            items, _, gone = _breakdown(run, d, cur, prev, None)
            rs = [{"name": i["name"], "before": i["before"] or 0, "now": i["value"], "diff": i["value"] - (i["before"] or 0)} for i in items]
            rs += [{"name": k, "before": v, "now": 0, "diff": -v} for k, v in gone]
            rs.sort(key=lambda r: -r["diff"])
            gross = sum(abs(r["diff"]) for r in rs)
            if not gross:
                continue
            same = sorted((r for r in rs if (r["diff"] * sign > 0 if sign else r["diff"] > 0)), key=lambda r: -abs(r["diff"]))
            against = sorted((r for r in rs if (r["diff"] * sign < 0 if sign else r["diff"] < 0)), key=lambda r: -abs(r["diff"]))
            if not same or (not sign and not against):
                continue
            per[d] = {"rows": rs, "same": same, "against": against, "score": sum(abs(r["diff"]) for r in same[:2]) / gross, "tidy": 3 <= len(rs) <= 20}
        if per:
            best = max(per, key=lambda d: (per[d]["tidy"], per[d]["score"]))
            dim = spec.get("why") if spec.get("why") in per else best
            run.by(dim, cur[0], cur[1], "why")
            P = per[dim]
            plain = lambda n: f"{dim} {n}" if str(n).strip().lower() in ("yes", "no", "true", "false", "y", "n", "0", "1", "not recorded") else n
            tag = lambda r: f"{plain(r['name'])} ({_signed(r['diff'])})"
            lead = P["same"][:1] + [r for r in P["same"][1:2] if abs(r["diff"]) >= 0.25 * abs(P["same"][0]["diff"])]
            opp = P["against"][0] if P["against"] else None
            why_parts = None
            if sign:
                s = f"{label} {'rose' if sign > 0 else 'fell'} by {short(abs(delta))} on {prev_label}, led by {_join(tag(r) for r in lead)}"
                tail = f", partly offset by {tag(opp)}." if opp and abs(opp["diff"]) >= 0.1 * abs(delta) else "."
                s += tail
                why_parts = [label, {"chip": f"{short(abs(delta))} on {prev_label}", "dir": "up" if sign > 0 else "down", "mood": moodof(sign > 0)},
                             f", led by {_join(tag(r) for r in lead)}{tail}"]
            else:
                s = f"{label} was level with {prev_label}: gains in {tag(P['same'][0])} were offset by {tag(opp)}."
            ups, downs = sum(1 for r in P["rows"] if r["diff"] > 0), sum(1 for r in P["rows"] if r["diff"] < 0)
            more = [B(f"Of {len(P['rows']):,} {dim} groups, **{ups or 'none'}** rose and **{downs or 'none'}** fell")]
            for d in [d for d in per if d != dim][:2]:
                top_d = per[d]["same"][0]
                more.append(B(f"By {d}, the largest contribution: **{tag(top_d)}**", top_d["diff"] > 0))
            WHY = [("change", "The change"), ("before", "Before and after")]
            kind = _chart_choice(spec, "why", WHY)
            big = sorted(sorted(P["rows"], key=lambda r: -abs(r["diff"]))[:8], key=lambda r: -r["diff"])
            if kind == "change":
                chart = {"type": "hbar", "labels": [r["name"] for r in big], "series": [{"name": f"Change on {prev_label}", "data": [r["diff"] for r in big]}], "x_title": dim, "y_title": f"Change in {label}",
                         "signed": True, "up_good": not lower_better, "values": True}
            else:
                chart = {"type": "hbar", "labels": [r["name"] for r in big], "series": [{"name": prev_label, "data": [r["before"] for r in big]}, {"name": plabel, "data": [r["now"] for r in big]}], "x_title": dim, "y_title": label}
            why_card = {"key": "why", "word": "Why", "ask": "Why did it change?", "sentence": s, "parts": why_parts, "more": more, "dims": list(per), "dim": dim,
                        "hero": {"big": _signed(delta) if unit != "%" else f"{delta:+.1f} pts", "small": f"vs {prev_label}", "dir": "up" if delta > 0 else "down" if delta < 0 else "flat", "mood": moodof(delta > 0) if delta else "neutral", "value": delta},
                        "mood": _mood(_pct(now, pv), lower_better, 0.5),
                        "chart_types": [{"key": k, "label": l} for k, l in WHY], "chart_type": kind, "chart": chart,
                        "table": {"columns": [dim, prev_label, plabel, "Change"],
                                  "rows": [[r["name"], r["before"], r["now"], r["diff"]] for r in P["rows"][:200]],
                                  "meta": {"abs": [3], "up_good": not lower_better}},
                        "note": "This shows where the figures moved. Your files do not record the reasons behind the movement, so none are given.",
                        "steps": [start] + notes + [f"Worked out {label} for each {dim} in {plabel} and in {prev_label}.",
                                                    "Subtracted one from the other. The differences add up to the overall change.",
                                                    "Named the groups that account for the most of it, and the largest one moving the other way.",
                                                    "When no grouping is chosen, the one whose two largest movers explain the biggest part of all movement is shown."],
                        "sql": run.sql.get("why")}
            cards.append(why_card)

    # ---------------- HOW: what to do next
    actions = []
    open_items = quality.check(base["id"])["summary"]["to_review"] if base["kind"] == "table" else 0
    if open_items:
        actions.append({"do": "Check the data before acting on these numbers.", "link": "data",
                        "why": f"“{base['name']}” still has {open_items} item{'s' if open_items != 1 else ''} to review, such as repeated rows or typing mistakes. They can change every figure in this story."})
    if tinfo:
        behind = sorted((i for i in tinfo["items"] if i["reached"] < tinfo["pace"] - 5), key=lambda i: i["reached"] - tinfo["pace"])
        over = sorted((i for i in tinfo["items"] if i["reached"] > tinfo["pace"] + 5), key=lambda i: -i["reached"])
        focus = (over if lower_better else behind)
        if focus:
            i = focus[0]
            need = f" To finish on {tinfo['word']} it needs about {short(i['need'])} a month; it has been averaging {short(i['avg'])}." if i["need"] and not lower_better and tinfo["left"] > 0 else ""
            actions.append({"do": f"Give {i['name']} attention: it is {'running over' if lower_better else 'behind'} its {tinfo['word']}.",
                            "why": f"{i['name']} has reached {i['reached']:.0f}% of its {tinfo['word']} for {tinfo['year']} with {tinfo['pace']:.0f}% of the year elapsed.{need}"})
        elif not lower_better:
            actions.append({"do": f"Keep the current course: every {tinfo['dim']} is on pace for its {tinfo['word']}.",
                            "why": f"{tinfo['reached']:.0f}% of the {tinfo['word']} for {tinfo['year']} is delivered with {tinfo['pace']:.0f}% of the year elapsed."})
    worry = [(m["dim"], m["up" if lower_better else "down"]) for m in moves if m["up" if lower_better else "down"]]
    cheer = [(m["dim"], m["down" if lower_better else "up"]) for m in moves if m["down" if lower_better else "up"]]
    if worry:
        dim, i = max(worry, key=lambda w: abs(w[1]["value"] - w[1]["before"]))
        actions.append({"do": f"Find out why {i['name']} {'rose' if lower_better else 'dropped'}.",
                        "why": f"{dim} {i['name']} went from {short(i['before'])} in {prev_label} to {short(i['value'])} in {plabel} ({'up' if i['change'] > 0 else 'down'} {abs(i['change']):.0f}%). It is the largest {'rise' if lower_better else 'fall'} in the period."})
    for m in (moves if M["additive"] else []):
        if m["count"] >= 4 and m["top"]["share"] >= 40 and m["top"]["name"] != "not recorded":
            actions.append({"do": f"Reduce the reliance on {m['top']['name']}.",
                            "why": f"{m['top']['name']} alone makes up {m['top']['share']:.0f}% of {label} across {m['count']:,} {m['dim']} groups. A problem there would hit the whole result."})
            break
    if cheer and not lower_better:
        dim, i = max(cheer, key=lambda w: abs(w[1]["value"] - w[1]["before"]))
        actions.append({"do": f"Learn from {i['name']} and repeat what worked.",
                        "why": f"{dim} {i['name']} went from {short(i['before'])} to {short(i['value'])} (up {abs(i['change']):.0f}%), the largest gain in the period."})
    actions = actions[:4]
    fc = None
    if series and len(series) >= 6 and (M["column"] or not value):
        fc = ml.forecast({"dataset": ds["id"], "date": date, "value": M["column"], "agg": "avg" if M["kind"] == "rate" else "sum", "horizon": 3, "filters": filters})
        if "error" in fc:
            fc = None
        else:
            tot, lo, hi = (sum(f[k] for f in fc["forecast"]) / (3 if M["kind"] == "rate" else 1) for k in ("value", "lo", "hi"))
            actions.append({"do": f"Estimate: about {short(tot)} {'a month on average' if M['kind'] == 'rate' else 'over the next 3 months'}.", "estimate": True,
                            "why": f"This is a forecast, not a fact. It is based on {len(fc['history'])} months of history; roughly {short(lo)} to {short(hi)} is likely. Reliability is {fc['reliability']['label'].lower()} ({fc['reliability']['score']} out of 100): {fc['reliability']['text'].split('. ', 1)[-1]}"})
    if not actions:
        actions.append({"do": "Nothing stands out that needs a decision right now.", "why": "No group moved sharply, nothing is far off target, and the data has no open issues."})
    cards.append({"key": "how", "word": "How", "ask": "How should we respond?", "sentence": actions[0]["do"], "more": [], "actions": actions,
                  "forecast": fc, "chart": None,
                  "table": fc["table"] if fc else None,
                  "note": "These steps come from fixed rules applied to your data: open data issues, distance from target, the biggest falls and rises, heavy reliance on one group, and a forecast. They are prompts for a decision, not instructions."
                          + (" The chart and table below are the forecast: an estimate, not a recorded figure." if fc else ""),
                  "steps": [start, "Checked the data check for open items.", "Compared progress against any target or budget found in your files.",
                            f"Took the biggest rise and fall between {prev_label} and {plabel}." if prev else "There is no earlier period to compare with, so rises and falls are not used.",
                            "Flagged any single group that makes up 40% or more of the total."]
                           + (["Forecast the next 3 months and reported how accurate that method was on past months."] if fc else []), "sql": None})

    title = f"{label}, {plabel}" + (f", {' and '.join(fwords)}" if fwords else "")
    files = ", ".join(dict.fromkeys(d["source"] for d in store.DATASETS.values() if d["kind"] == "table"))
    for c in cards:
        c["bullets"] = [b if isinstance(b, dict) else {"t": b, "dir": None, "mood": None} for b in c.get("more", [])]
        c["more"] = [b["t"].replace("**", "") + ("" if b["t"].endswith((".", "?", "!")) else ".") for b in c["bullets"]]
    lines = [title, ""]
    for c in cards:
        if c["key"] == "how":
            lines.append("HOW (suggested next steps)")
            lines += [f"  {i}. {a['do']} {a['why']}" for i, a in enumerate(actions, 1)]
        else:
            lines.append(f"{c['word'].upper()}: {c['sentence']} {' '.join(c['more'])}".strip())
    lines += ["", f"Source: {files}. Worked out from the uploaded files only."]
    for c in cards:
        c.setdefault("mood", "neutral")      # Who, Which and How describe; they do not judge
        c.setdefault("brief", {"text": c["sentence"]})
        if (c.get("hero") or {}).get("value") is not None:
            c["brief"]["value"] = c["hero"]["value"]
    rec = MS.reconcile(ds, base, M, where, params, fwords, cur, plabel, now, date, run.count(*cur) if cur else run.count())
    lines.insert(1, rec["line"])
    by_key = {c["key"]: c for c in cards}
